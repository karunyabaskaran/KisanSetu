class I18nService {
    constructor() {
        this.currentLang = localStorage.getItem("kisansetu_lang") || "en";
    }

    setLanguage(langCode) {
        this.currentLang = langCode;
        localStorage.setItem("kisansetu_lang", langCode);
        this.applyTranslations();
        window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: langCode } }));
    }

    autoDetectFromLocation(stateName, districtName) {
        const stateKey = Object.keys(STATE_TO_LANGUAGE).find(
            s => s.toLowerCase() === (stateName || "").toLowerCase().trim()
        );
        if (stateKey) {
            const detected = STATE_TO_LANGUAGE[stateKey];
            console.log(`[i18n] Auto-detected regional language for '${stateName}': ${detected}`);
            this.setLanguage(detected);
            return detected;
        }
        return this.currentLang;
    }

    t(key) {
        // First check active language dictionary
        const dict = TRANSLATIONS[this.currentLang];
        if (dict && dict[key]) return dict[key];

        // Check regional fallback bases
        if (REGIONAL_FALLBACK_BASES[this.currentLang] && REGIONAL_FALLBACK_BASES[this.currentLang][key]) {
            return REGIONAL_FALLBACK_BASES[this.currentLang][key];
        }

        // Secondary fallback to Hindi for Northern/Western/Eastern or English
        if (this.currentLang !== "en" && TRANSLATIONS["hi"] && TRANSLATIONS["hi"][key]) {
            // For Hindi-family languages
            if (["mai", "sat", "doi", "kok", "sa", "ne", "brx"].includes(this.currentLang)) {
                return TRANSLATIONS["hi"][key];
            }
        }

        // Default to English
        return (TRANSLATIONS["en"] && TRANSLATIONS["en"][key]) || key;
    }

    translateCrop(cropName) {
        if (!cropName) return "";
        const cropKeyMap = {
            "Ponni Raw Rice (Organic)": "crop_ponni_rice",
            "1121 Traditional Basmati Rice": "crop_basmati_rice",
            "Nashik Red Onions": "crop_nashik_onion",
            "Sharbati Golden Wheat": "crop_sharbati_wheat",
            "Country Small Onions (Shallots)": "crop_small_onions",
            "Thompson Seedless Grapes": "crop_grapes"
        };
        const key = cropKeyMap[cropName];
        if (key) {
            const trans = this.t(key);
            if (trans && trans !== key) return trans;
        }
        return cropName;
    }

    translateTrend(trendStr) {
        if (!trendStr) return "";
        const match = trendStr.match(/([+-\d%]+)\s*\(([^)]+)\)/);
        if (match) {
            const pct = match[1];
            const word = match[2].trim().toLowerCase();
            const wordMap = {
                high: "trend_high",
                surge: "trend_surge",
                volatile: "trend_volatile",
                stable: "trend_stable",
                moderate: "trend_moderate",
                "peak season": "trend_peak_season"
            };
            const key = wordMap[word];
            if (key) {
                const trans = this.t(key);
                if (trans && trans !== key) return `${pct} (${trans})`;
            }
        }
        return trendStr;
    }

    translateInsight(insightStr, cropName) {
        if (!insightStr) return "";
        const insightKeyMap = {
            "Strong South Indian domestic demand": "insight_south_demand",
            "Export momentum to Gulf & Middle East": "insight_gulf_export",
            "Post-monsoon replenishment cycle": "insight_monsoon_cycle",
            "Consistent household milling demand": "insight_milling_demand",
            "Steady demand in southern culinary zones": "insight_culinary_demand",
            "High retail supermarket uptake": "insight_supermarket_uptake"
        };
        const key = insightKeyMap[insightStr];
        if (key) {
            const trans = this.t(key);
            if (trans && trans !== key) return trans;
        }
        return insightStr;
    }

    applyTranslations() {
        // 1. Text elements with data-i18n
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            const translation = this.t(key);
            if (translation) {
                el.textContent = translation;
            }
        });

        // 2. Input and textarea placeholders with data-i18n-placeholder
        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            const translation = this.t(key);
            if (translation) {
                el.placeholder = translation;
            }
        });

        // 3. Elements with title tooltips
        document.querySelectorAll("[data-i18n-title]").forEach(el => {
            const key = el.getAttribute("data-i18n-title");
            const translation = this.t(key);
            if (translation) {
                el.title = translation;
            }
        });

        // 4. Update language selector value
        const selector = document.getElementById("languageSelector");
        if (selector) {
            selector.value = this.currentLang;
        }

        // 5. Update active role badges if any
        document.querySelectorAll(".role-badge").forEach(el => {
            if (el.classList.contains("role-farmer")) el.textContent = this.t("role_farmer").toUpperCase();
            if (el.classList.contains("role-buyer")) el.textContent = this.t("role_buyer").toUpperCase();
            if (el.classList.contains("role-logistics")) el.textContent = this.t("role_logistics").toUpperCase();
            if (el.classList.contains("role-admin")) el.textContent = this.t("role_admin").toUpperCase();
        });

        // 6. Update active portal header title if present
        const activePortalTitle = document.getElementById("activePortalTitle");
        if (activePortalTitle && window.currentRole) {
            const roleKey = "role_" + window.currentRole;
            activePortalTitle.textContent = (this.t(roleKey) || window.currentRole) + " Portal";
        }
    }
}

